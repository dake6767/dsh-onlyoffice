/**
 * Two-pass esbuild build for the dsh-onlyoffice browser artifact.
 *
 *   1. `vendor/onlyoffice-web-comp/internal/editor/x2t.worker.ts` → a standalone
 *      IIFE worker bundle (x2t worker + vendored brotli decoder). Its source is
 *      embedded as a string into a generated module, because the DSH client
 *      artifact must be ONE file: the worker is constructed from a Blob URL
 *      (see vendor/PATCHES.md, patch 1).
 *   2. `src/client/index.jsx` → `lib/client.js`, a CJS closure factory in the
 *      DSH module-loader shape. React / cordis / client-runtime stay external
 *      and resolve through the loader module table.
 *
 * No code splitting, no `import.meta`, no extra asset files.
 *
 * Usage: node build/build-client.mjs [--minify]
 */

import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));
const MINIFY = process.argv.includes('--minify');

/** Bundle id = package name; the client module loader keys on it. */
const CLIENT_ID = '@dake6767/dsh-onlyoffice';

/** Module specifiers the web shell shares into the frozen module table. */
const CLIENT_EXTERNALS = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  '@deepseek-ai/dsh-client-runtime',
  '@deepseek-ai/dsh-client-runtime/client',
];

const TARGET = ['chrome110', 'edge110', 'firefox115', 'safari16'];

const GENERATED_DIR = join(ROOT, 'build', 'generated');
const WORKER_ENTRY = join(
  ROOT,
  'vendor',
  'onlyoffice-web-comp',
  'internal',
  'editor',
  'x2t.worker.ts',
);
const WORKER_OUT = join(GENERATED_DIR, 'x2t.worker.iife.js');
const WORKER_SOURCE_MODULE = join(GENERATED_DIR, 'x2t-worker-source.js');
const CLIENT_ENTRY = join(ROOT, 'src', 'client', 'index.jsx');
const CLIENT_OUT = join(ROOT, 'lib', 'client.js');

const DEFINE = {
  'process.env.NODE_ENV': '"production"',
};

function formatBytes(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(2)} MiB (${bytes.toLocaleString('en-US')} bytes)`;
}

async function buildWorker() {
  await build({
    absWorkingDir: ROOT,
    entryPoints: [WORKER_ENTRY],
    outfile: WORKER_OUT,
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: TARGET,
    charset: 'utf8',
    minify: MINIFY,
    legalComments: 'none',
    define: DEFINE,
    logLevel: 'warning',
  });

  const source = await readFile(WORKER_OUT, 'utf8');

  if (/\bimport\.meta\b/.test(source)) {
    throw new Error('The x2t worker bundle still contains import.meta.');
  }

  const moduleSource = [
    '// AUTO-GENERATED by build/build-client.mjs — do not edit.',
    '// Inlined IIFE source of the x2t conversion worker (classic worker, Blob URL).',
    `export const X2T_WORKER_SOURCE = ${JSON.stringify(source)};`,
    '',
  ].join('\n');

  await writeFile(WORKER_SOURCE_MODULE, moduleSource, 'utf8');
  return { workerBytes: Buffer.byteLength(source, 'utf8') };
}

async function buildClient() {
  const banner = [
    `window.__ModuleLoader__.load({ id: ${JSON.stringify(CLIENT_ID)}, factory: (require) => {`,
    'var module = { exports: {} }; var exports = module.exports;',
  ].join('\n');
  const footer = 'return module.exports; } });\n';

  await build({
    absWorkingDir: ROOT,
    entryPoints: [CLIENT_ENTRY],
    outfile: CLIENT_OUT,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: TARGET,
    jsx: 'automatic',
    external: CLIENT_EXTERNALS,
    define: DEFINE,
    charset: 'utf8',
    minify: MINIFY,
    legalComments: 'none',
    banner: { js: banner },
    footer: { js: footer },
    logLevel: 'warning',
  });

  const text = await readFile(CLIENT_OUT, 'utf8');
  if (/\bimport\.meta\b/.test(text)) {
    throw new Error('The client bundle still contains import.meta.');
  }
  if (text.includes('exceljs')) {
    throw new Error('The client bundle still references the removed exceljs dependency.');
  }

  const info = await stat(CLIENT_OUT);
  return { clientBytes: info.size };
}

async function main() {
  await mkdir(GENERATED_DIR, { recursive: true });
  await mkdir(dirname(CLIENT_OUT), { recursive: true });
  await mkdir(dirname(CLIENT_ENTRY), { recursive: true });

  console.log('[dsh-onlyoffice] building x2t worker (IIFE)…');
  const { workerBytes } = await buildWorker();
  console.log(`  → ${WORKER_OUT.replace(ROOT + '/', '')} · ${formatBytes(workerBytes)}`);

  console.log('[dsh-onlyoffice] building client bundle (CJS factory)…');
  const { clientBytes } = await buildClient();
  console.log(`  → ${CLIENT_OUT.replace(ROOT + '/', '')} · ${formatBytes(clientBytes)}`);

  const limit = 3 * 1024 * 1024;
  if (clientBytes >= limit) {
    throw new Error(`lib/client.js is ${formatBytes(clientBytes)}, over the 3 MiB budget.`);
  }

  console.log('[dsh-onlyoffice] client build OK');
}

main().catch((error) => {
  console.error('[dsh-onlyoffice] build failed:', error && error.message ? error.message : error);
  process.exitCode = 1;
});
